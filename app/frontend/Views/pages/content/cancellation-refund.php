<h2>Cancelling an order</h2>
<ul>
  <li>Orders can be cancelled free of charge any time <strong>before they are shipped</strong>.</li>
  <li>Go to <a href="<?= APP_URL ?>/account/orders">My Account → My Orders</a>, open the order and choose <strong>Cancel</strong>.</li>
  <li>Once an item is shipped, it can no longer be cancelled — but you can refuse the delivery or request a return after it arrives.</li>
</ul>

<h2>Refund timelines</h2>
<table>
  <tr><th>Payment method</th><th>Refund time after approval</th></tr>
  <tr><td>Store Wallet</td><td>Instant</td></tr>
  <tr><td>UPI / Net-banking</td><td>3–5 business days</td></tr>
  <tr><td>Credit / Debit card</td><td>5–7 business days</td></tr>
  <tr><td>Cash on Delivery</td><td>Refunded to your store wallet, or bank transfer on request (5–7 days)</td></tr>
</table>

<h2>What gets refunded</h2>
<ul>
  <li><strong>Cancellation before shipping:</strong> 100% of the amount paid, including shipping.</li>
  <li><strong>Approved return:</strong> full item price; original shipping is refunded only if the item was defective, damaged or wrong.</li>
  <li><strong>Coupons / points used:</strong> coupon value is not re-issued in cash; loyalty points used are credited back to your account.</li>
</ul>

<h2>Refund not received?</h2>
<p>If a refund hasn't arrived after the timeline above, first check with your bank, then reach us via <a href="<?= APP_URL ?>/info/contact-us">Contact Us</a> with your order number — we'll trace it within 48 hours.</p>
