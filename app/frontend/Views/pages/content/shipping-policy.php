<h2>Order tracking</h2>
<p>Once shipped, you'll receive the courier name and tracking number by notification and email. Track any order anytime on our <a href="<?= APP_URL ?>/track">Track Order</a> page.</p>

<h2>Delivery attempts</h2>
<p>Couriers make up to 3 delivery attempts. If all fail, the item returns to the vendor and the order is refunded (minus shipping for COD refusals).</p>

<h2>Cash on Delivery (COD)</h2>
<p>COD is available on most items. Please keep the exact amount ready — delivery executives may not carry change.</p>
