<p>We want you to love what you ordered. If something isn't right, our return process is simple and hassle-free.</p>

<h2>Return window</h2>
<p>Most products can be returned within <strong>7 days of delivery</strong>. The item must be unused, in its original packaging, with all tags, accessories and the invoice.</p>

<h2>How to request a return</h2>
<ol>
  <li>Go to <a href="<?= APP_URL ?>/account/orders">My Account → My Orders</a> and open the delivered order.</li>
  <li>Click <strong>Request Return</strong>, choose <em>Return</em> or <em>Replacement</em>, and tell us the reason.</li>
  <li>Our team (or the vendor) reviews the request — you'll get a notification once it's approved.</li>
  <li>Hand the item to the pickup executive or ship it back as instructed.</li>
</ol>

<h2>Non-returnable items</h2>
<ul>
  <li>Perishable goods (fresh grocery, food items).</li>
  <li>Personal care and beauty products that have been opened or used.</li>
  <li>Innerwear, socks and similar hygiene-sensitive apparel.</li>
  <li>Digital goods, gift cards and vouchers.</li>
</ul>

<h2>Refunds after return</h2>
<p>Once the returned item passes a quality check, your refund is issued to your <strong>original payment method or store wallet</strong> within 5–7 business days. Wallet refunds are instant on approval. See our <a href="<?= APP_URL ?>/info/cancellation-refund">Cancellation &amp; Refund policy</a> for details.</p>

<h2>Damaged or wrong item received?</h2>
<p>Raise a return request within 48 hours of delivery with photos of the item and packaging — these cases get priority replacement at no cost to you.</p>
